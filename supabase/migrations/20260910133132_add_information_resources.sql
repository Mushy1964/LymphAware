create or replace function public.withdraw_profile_health_consent(
  p_profile_id uuid,
  p_version text,
  p_statement text
)
returns timestamptz
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_user uuid := auth.uid();
  v_time timestamptz := now();
begin
  if v_user is null then
    raise exception 'Authentication required';
  end if;
  if not exists (
    select 1 from public.profiles
    where id = p_profile_id and user_id = v_user and is_demo = false
  ) then
    raise exception 'Profile not found';
  end if;

  insert into public.profile_privacy_events(profile_id,user_id,event_type,version,statement,created_at)
  values (p_profile_id,v_user,'HEALTH_CONSENT_WITHDRAWN',p_version,p_statement,v_time);

  update public.profiles
  set lymphoedema_type = null,
      lymphoedema_location = null,
      compression_information = null,
      treatment_considerations = null,
      assistance_needs = null,
      emergency_contact_name = null,
      emergency_contact_relationship = null,
      emergency_contact_phone = null,
      additional_statement = null,
      qr_profile_active = false,
      updated_at = v_time
  where id = p_profile_id and user_id = v_user;

  delete from public.profile_assistance where profile_id = p_profile_id;
  delete from public.profile_information_resources where profile_id = p_profile_id;

  update public.language_profiles
  set qr_profile_active = false,
      translated_content = '{}'::jsonb,
      translation_generated_at = null,
      translation_source_updated_at = null,
      translation_error = null,
      updated_at = v_time
  where source_profile_id = p_profile_id and user_id = v_user;

  return v_time;
end;
$$;
